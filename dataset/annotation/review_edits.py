rows = list(csv.DictReader(open(os.path.join(ANN, "social_test_sheet.tsv"), encoding="utf-8"), delimiter="\t"))
missing = []
with open(os.path.join(ANN, "social_test_edits.tsv"), "w", encoding="utf-8", newline="") as fe, \
        open(os.path.join(ANN, "social_test_gold.tsv"), "w", encoding="utf-8", newline="") as fg:
    we = csv.writer(fe, delimiter="\t", lineterminator="\n")
    wg = csv.writer(fg, delimiter="\t", lineterminator="\n")
    we.writerow(["row", "id", "old", "new"])
    wg.writerow(["id", "status", "gold", "annotator", "note"])
    for i, r in enumerate(rows):
        g = r["auto_gold"]
        if i in SKIP:
            wg.writerow([r["id"], "skip", g, "claude-review", SKIP[i]])
            continue
        for old, new in E.get(i, []):
            pat = r"(?<!\S)" + re.escape(old) + r"(?!\S)"
            if not re.search(pat, g):
                missing.append((i, old, g))
                continue
            g = re.sub(pat, new, g)
            we.writerow([i, r["id"], old, new])
        wg.writerow([r["id"], "edited" if i in E else "ok", g, "claude-review", ""])
print("rows", len(rows), "edited", len(E), "skipped", len(SKIP))
for m in missing:
    print("NOT FOUND", m)
